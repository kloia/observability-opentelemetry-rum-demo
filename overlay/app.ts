// Static import, evaluated before anything below: instrumentation must patch http/express
// before `./server` (which requires them) is ever dynamically imported.
import './tracing'

async function app () {
  const { default: validateDependencies } = await import('./lib/startup/validateDependenciesBasic')
  await validateDependencies()

  const server = await import('./server')
  await server.start()
}

app()
  .catch(err => {
    throw err
  })
